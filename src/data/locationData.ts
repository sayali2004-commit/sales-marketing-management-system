export const employeeLocationSummaries = employees
export const locationVisitEntries = visitEntries

export function getEmployeeDayTravels(employeeId: string): EmployeeDayTravel[] {
  const entries = locationVisitEntries
    .filter((e) => e.employeeId === employeeId)
    .sort((a, b) => (a.date === b.date ? a.time.localeCompare(b.time) : b.date.localeCompare(a.date)))

  const byDate = new Map<string, LocationVisitEntry[]>()
  entries.forEach((entry) => {
    const list = byDate.get(entry.date) || []
    list.push(entry)
    byDate.set(entry.date, list)
  })

  return Array.from(byDate.entries()).map(([date, dayEntries]) => {
    const sorted = [...dayEntries].sort((a, b) => a.order - b.order)
    const uniqueLocations = new Set(sorted.map((e) => e.locationName))
    return {
      employeeId,
      date,
      startingPoint: sorted[0]?.startingPoint || 'Office',
      route: sorted.map((e) => e.locationName),
      totalDistanceKm: sorted.reduce((s, e) => s + e.distanceKm, 0),
      locationsVisited: uniqueLocations.size,
      visits: sorted.filter((e) => e.purpose !== 'Return to office').length,
      entries: sorted,
    }
  })
}

export function getAllDayTravels(): EmployeeDayTravel[] {
  return employees.flatMap((e) => getEmployeeDayTravels(e.employeeId))
}

export function formatDateLong(date: string) {
  const d = new Date(`${date}T00:00:00`)
  return d.toLocaleDateString('en-US', { day: 'numeric', month: 'long', year: 'numeric' })
}

export function formatTime12(time: string) {
  const [h, m] = time.split(':')
  const hour = Number(h)
  const suffix = hour >= 12 ? 'PM' : 'AM'
  const hour12 = hour % 12 || 12
  return `${hour12}:${m} ${suffix}`
}
